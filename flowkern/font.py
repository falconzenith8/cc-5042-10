_TOFU = ["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"]


def glyph_rows(ch: str) -> list[str]:
    if ch in _GLYPHS:
        return _GLYPHS[ch]
    up = ch.upper()
    if up in _GLYPHS:
        return _GLYPHS[up]
    return _TOFU


def line_width(text: str, scale: float) -> float:
    n = len(text)
    if n == 0:
        return 0.0
    # Advance between glyph origins is ADVANCE; the final glyph's last
    # column still occupies one scale unit after its origin.
    return ((n - 1) * ADVANCE + GLYPH_W + 1) * scale


def text_size(text: str, scale: float) -> tuple[float, float]:
    lines = text.split("\n")
    w = max((line_width(line, scale) for line in lines), default=0.0)
    h = (GLYPH_H * len(lines)
         + (LINE_H - GLYPH_H) * max(0, len(lines) - 1)) * scale
    return w, h
